function russianCount(value: string, singular: string, paucal: string, plural: string) {
  const count = Number(value);
  const lastTwo = count % 100;
  const last = count % 10;
  const noun = lastTwo >= 11 && lastTwo <= 14 ? plural : last === 1 ? singular : last >= 2 && last <= 4 ? paucal : plural;
  return `${value} ${noun}`;
}

function translateDynamicText(source: string, language: LocalizedLanguage) {
  const moduleMatch = source.match(/^(\d+)\s+mod[üÜ]l(?:\s+ba[ğĞ]l[ıI])?$/iu);
  if (moduleMatch) {
    const prefix = moduleMatch[1];
    if (language === "az") return `${prefix} modul bağlıdır`;
    if (language === "ru") return `${russianCount(prefix, "модуль", "модуля", "модулей")} подключено`;
    if (language === "it") return `${prefix} moduli collegati`;
    if (language === "de") return `${prefix} Module verbunden`;
    return `${prefix} modules connectés`;
  }
  const floorHeight = source.match(/^(\d+)\s+kat\s+·\s+([\d.,]+)\s+m$/iu);
  if (floorHeight) {
    if (language === "az") return `${floorHeight[1]} mərtəbə · ${floorHeight[2]} m`;
    if (language === "ru") return `${russianCount(floorHeight[1], "этаж", "этажа", "этажей")} · ${floorHeight[2]} м`;
    if (language === "it") return `${floorHeight[1]} piani · ${floorHeight[2]} m`;
    if (language === "de") return `${floorHeight[1]} Geschosse · ${floorHeight[2]} m`;
    return `${floorHeight[1]} niveaux · ${floorHeight[2]} m`;
  }
  const floor = source.match(/^(\d+)\s+kat$/iu);
  if (floor) {
    if (language === "az") return `${floor[1]} mərtəbə`;
    if (language === "ru") return russianCount(floor[1], "этаж", "этажа", "этажей");
    if (language === "it") return `${floor[1]} piani`;
    if (language === "de") return `${floor[1]} Geschosse`;
    return `${floor[1]} niveaux`;
  }
  const step = source.match(/^ADIM\s+(\d+)\s+\/\s+(\d+)$/iu);
  if (step) {
    if (language === "az") return `ADDIM ${step[1]} / ${step[2]}`;
    if (language === "ru") return `ШАГ ${step[1]} / ${step[2]}`;
    if (language === "it") return `PASSAGGIO ${step[1]} / ${step[2]}`;
    if (language === "de") return `SCHRITT ${step[1]} / ${step[2]}`;
    return `ÉTAPE ${step[1]} / ${step[2]}`;
  }
  return null;
}

export function translateText(value: string, language: SiteLanguage, catalogue?: TranslationCatalogue) {
  if (language === "tr" || !value) return value;
  if (language === "en") return translateTextToEnglish(value);
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const source = value.trim();
  if (!source) return value;
  const v3Translation = v3Translations[language][source];
  if (v3Translation) return `${leading}${correctLocalizedTechnicalTerms(v3Translation, language)}${trailing}`;
  const override = localizedOverrides[language][source];
  if (override) return `${leading}${override}${trailing}`;
  const exactTranslation = catalogue?.[source];
  if (exactTranslation) return `${leading}${correctLocalizedTechnicalTerms(exactTranslation, language)}${trailing}`;
  const dynamicTranslation = translateDynamicText(source, language);
  if (dynamicTranslation) return `${leading}${dynamicTranslation}${trailing}`;
  return value;
}

