const catalogueLoaders: Record<LocalizedLanguage, () => Promise<{ default: TranslationCatalogue }>> = {
  az: () => import("./i18n-az.json"),
  ru: () => import("./i18n-ru.json"),
  it: () => import("./i18n-it.json"),
  de: () => import("./i18n-de.json"),
  fr: () => import("./i18n-fr.json"),
};

const cataloguePromises = new Map<LocalizedLanguage, Promise<TranslationCatalogue>>();

export function loadTranslationCatalogue(language: SiteLanguage): Promise<TranslationCatalogue | undefined> {
  if (language === "tr" || language === "en") return Promise.resolve(undefined);
  let promise = cataloguePromises.get(language);
  if (!promise) {
    promise = catalogueLoaders[language]()
      .then((module) => module.default)
      .catch((error) => {
        cataloguePromises.delete(language);
        throw error;
      });
    cataloguePromises.set(language, promise);
  }
  return promise;
}

