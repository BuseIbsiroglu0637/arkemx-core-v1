export function translateTextToEnglish(value: string) {
  if (!value || !/[A-Za-zÇĞİÖŞÜçğıöşü]/.test(value)) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const source = value.trim();
  if (!source) return value;

  const v3Translation = v3Translations.en[source];
  if (v3Translation) return `${leading}${correctTechnicalEnglish(v3Translation)}${trailing}`;
  const exactTranslation = exact[source];
  if (exactTranslation) return `${leading}${correctTechnicalEnglish(exactTranslation)}${trailing}`;
  const automaticTranslation = (automaticTranslations as Record<string, string>)[source];
  if (automaticTranslation) return `${leading}${correctTechnicalEnglish(automaticTranslation)}${trailing}`;

  for (const [pattern, formatter] of dynamicPatterns) {
    const match = source.match(pattern);
    if (match) return `${leading}${correctTechnicalEnglish(formatter(...match.slice(1)))}${trailing}`;
  }

  let translated = source;
  for (const [from, to] of fragments) {
    const escaped = from.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const pattern = new RegExp(`(?<![\\p{L}\\p{N}])${escaped}(?![\\p{L}\\p{N}])`, "gu");
    translated = translated.replace(pattern, to);
  }

  /*
   * Do not expose hybrid, broken sentences. Exact catalogue entries cover
   * customer-facing copy; conservative fragment translation is reserved for
   * short technical labels whose remaining vocabulary is already English.
   */
  const residualTurkish = /[ÇĞİÖŞÜçğıöşü]|\b(?:bir|bu|şu|her|olarak|göre|üzerinden|kadar|daha|ancak|yalnız|nasıl|neden|gerekir|amaç|içerik|bilgi|kayıt|yönetim|görünüm|sahada|tarafından|olmadan|olduğu|üretim|uygulama|teslim|kalite|tedarik|onay|bakım|varlık|risk|sorumlu|sorun|dosya|doğru|önce|sonra|arasında|üzerinde|oluşur|sağlar|tanımlar|dönüştürür|gösterir|kullanılır)\b/iu.test(translated);
  if (residualTurkish && translated !== source) return value;
  return `${leading}${correctTechnicalEnglish(translated)}${trailing}`;
}

